export const LANGS = [
  { id: 'ru', label: 'Русский' },
  { id: 'en', label: 'English' }
]

// the phone's own language on first launch: Russian for ru, English otherwise
export function deviceLang() {
  try {
    return /^ru/i.test(Intl.DateTimeFormat().resolvedOptions().locale) ? 'ru' : 'en'
  } catch {
    return 'ru'
  }
}

let current = 'ru'

export function setLang(lang) {
  current = STRINGS[lang] ? lang : 'ru'
}

export function t(key, vars) {
  const s = STRINGS[current][key] ?? STRINGS.ru[key] ?? key
  if (!vars) return s
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m))
}

// Components call useT() instead of importing t directly: reading the context
// makes them re-render when the language changes.
export const LangContext = createContext('ru')
export function useT() {
  useContext(LangContext)
  return t
}
